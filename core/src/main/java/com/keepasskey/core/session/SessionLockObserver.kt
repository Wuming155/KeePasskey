package com.keepasskey.core.session

/**
 * 密码库会话终止（锁定/关闭）观察者（ISSUE-P1-07）。
 *
 * 触发时机：会话进入 `LOCKED`（锁定）或 `CLOSED`（关闭）态的**同步收尾阶段**——
 * 此刻内存主凭据与数据库树均已销毁。凡由会话派生出的敏态产物
 * （典型如 `cacheDir/sync` 下的 KDBX 密文快照 `.cache` / `.basecache`）必须由
 * 各自的持有方在同一时机清理，否则「锁定」在数据生命周期意义上缺少终止点：
 * 设备失窃后攻击者可对残留密文快照无限期离线爆破主密码。
 *
 * 实现契约：
 * 1. **非阻塞**：回调在会话互斥锁内同步触发，实现只可做删除缓存目录一类轻量操作，
 *    严禁执行网络/大量 IO，更严禁在回调内再次调用会话 API（必然重入死锁）；
 * 2. **幂等**：同一会话可被反复锁定，重复调用不得报错；
 * 3. **自容错**：会话为保证「锁定」原子性会吞掉回调抛出的异常，
 *    因此实现必须自行兜住失败并记录（例如写入调试日志），
 *    绝不可依赖异常向上传播。
 */
fun interface SessionLockObserver {

    /**
     * 会话已终止（锁定或关闭），请立即清理与本会话关联的敏态派生数据。
     */
    fun onSessionLocked()
}
